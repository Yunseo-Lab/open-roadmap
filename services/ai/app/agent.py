from .schemas import AgentOperation, GraphEdge, GraphNode, RoadmapAgentRequest, RoadmapAgentResponse


def build_graph_response(request: RoadmapAgentRequest) -> RoadmapAgentResponse:
    graph = request.graph.model_copy(deep=True)

    if not graph.nodes:
        objective_id = "objective-main"
        milestone_id = "milestone-first"
        event_id = "event-log"
        graph.nodes.extend(
            [
                GraphNode(
                    id=objective_id,
                    type="objective",
                    position={"x": 80, "y": 140},
                    data={
                        "title": request.message[:72] or "Core objective",
                        "description": "Draft objective generated by the Python AI service.",
                        "status": "active",
                        "metadata": {},
                    },
                ),
                GraphNode(
                    id=milestone_id,
                    type="milestone",
                    position={"x": 420, "y": 80},
                    data={
                        "title": "First milestone",
                        "description": "Break down the objective into an actionable stage.",
                        "status": "planned",
                        "metadata": {},
                    },
                ),
                GraphNode(
                    id=event_id,
                    type="event",
                    position={"x": 420, "y": 260},
                    data={
                        "title": "Progress log",
                        "description": "Capture work, learnings, and artifacts as events.",
                        "status": "planned",
                        "metadata": {},
                    },
                ),
            ]
        )
        graph.edges.extend(
            [
                GraphEdge(
                    id="milestone-first-supports-objective-main",
                    source=milestone_id,
                    target=objective_id,
                    label="supports",
                    data={"kind": "supports", "label": "supports", "metadata": {}},
                ),
                GraphEdge(
                    id="event-log-next-milestone-first",
                    source=event_id,
                    target=milestone_id,
                    label="next",
                    data={"kind": "next", "label": "next", "metadata": {}},
                ),
            ]
        )

    return RoadmapAgentResponse(
        graph=graph,
        summary="Python AI service returned a roadmap draft.",
        operations=[
            AgentOperation(
                tool="python_service_contract",
                args={"artifactIds": request.artifactIds},
                result={"ok": True, "nodes": len(graph.nodes), "edges": len(graph.edges)},
            )
        ],
    )
